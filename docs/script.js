const languageButton = document.querySelector('.language-toggle');
const languageOptions = document.querySelectorAll('.language-option');

function setLanguage(language) {
  const copy = translations[language];
  document.documentElement.lang = language === 'zh' ? 'zh-CN' : 'en';
  document.title = language === 'zh' ? '凌钰棋 | 个人主页' : 'Ling Yuqi | Personal Profile';
  document.querySelectorAll('[data-i18n]').forEach((element) => {
    const key = element.dataset.i18n;
    if (copy[key]) element.textContent = copy[key];
  });
  languageOptions.forEach((option) => {
    const active = option.dataset.language === language;
    option.classList.toggle('is-active', active);
  });
  languageButton.setAttribute('aria-pressed', String(language === 'en'));
  languageButton.setAttribute('aria-label', language === 'zh' ? 'Switch to English' : '切换为中文');
  try { localStorage.setItem('profile-language', language); } catch (_) {}
}

languageButton.addEventListener('click', () => {
  const nextLanguage = document.documentElement.lang === 'zh-CN' ? 'en' : 'zh';
  setLanguage(nextLanguage);
});

let savedLanguage = 'zh';
try { savedLanguage = localStorage.getItem('profile-language') || 'zh'; } catch (_) {}
setLanguage(savedLanguage === 'en' ? 'en' : 'zh');
